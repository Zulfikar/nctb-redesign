function colEx(expr, mk, more = {}) {
  const t = expr.split(/\s*([+−])\s*/), nums = t.filter((_, i) => i % 2 === 0), ops = t.filter((_, i) => i % 2 === 1);
  // the boxes depend only on the question: an addition gets the longest number's digits + 1, a subtraction its digits
  const boxes = Math.max(...nums.map((n) => [...n].length)) + (ops.includes("+") ? 1 : 0);
  return { mk, rows: nums.map((n, i) => (i === nums.length - 1 ? ops[ops.length - 1] : "") + n), ans: "", boxes, ...more };
}
