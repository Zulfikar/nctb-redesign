/** A column exercise from "৫৩৯৭ − ৯২৮": the rows, and a dashed box for each place the answer may need. The boxes depend only on
 *  the question (an addition: its longest number's digits + 1; a subtraction: its longest number's digits), never on the answer. */
function colEx(expr, mk) {
  const t = expr.split(/\s*([+−])\s*/), nums = t.filter((_, i) => i % 2 === 0), ops = t.filter((_, i) => i % 2 === 1);
  const boxes = Math.max(...nums.map((n) => [...n].length)) + (ops.includes("+") ? 1 : 0);
  return { mk, rows: nums.map((n, i) => (i === nums.length - 1 ? ops[ops.length - 1] : "") + n), ans: "", boxes };
}
